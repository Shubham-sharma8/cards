const BY_SLUG = new Map<string, BankHelpEntry>(
  BANK_HELP_DIRECTORY.map((e) => [e.bank_slug, e])
);

export function getBankHelpBySlug(bankSlug: string | null | undefined): BankHelpEntry | null {
  if (!bankSlug) return null;
  return BY_SLUG.get(bankSlug.trim().toLowerCase()) || null;
}

export function searchBankHelp(query: string): BankHelpEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return BANK_HELP_DIRECTORY;
  return BANK_HELP_DIRECTORY.filter((b) =>
    `${b.bank} ${b.bank_slug} ${b.tierType} ${b.helplineTollFree} ${b.l1Email} ${b.l2NodalEmail} ${b.l3PnoEmail}`
      .toLowerCase()
      .includes(q)
  );
}
